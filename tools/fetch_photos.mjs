// Download reference photos from Wikimedia Commons into the app (run by the owner; Node 18+).
//   node tools/fetch_photos.mjs
// Writes img/photos/*, src/photos.js (credits from the Commons API) and the photo list in sw.js.
// Review the printed list before committing: every photo must clearly show the stated species or nest.
import { mkdirSync, writeFileSync, readFileSync, readdirSync, unlinkSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const API = "https://commons.wikimedia.org/w/api.php";
const UA = "VespaControl/1.0 (https://github.com/araya906/vespa-control)";
const WIDTH = 500; // a standard Commons thumbnail width
const PER_GROUP = 3;
// Titles shown with [CHECK] that turn out wrong: add them here and run the script again.
const EXCLUDE = new Set([]);

// Curated titles first; if fewer than PER_GROUP exist, fill from a Commons search whose file names match `must`.
const GROUPS = {
  velutina: { titles: ["Vespa velutina 165382529.jpg", "Asian hornet (33252984804) (2).jpg", "Vespa velutina nigrithorax MHNT dos.jpg"],
    search: "Vespa velutina", must: /velutina/i, not: /nest|nid|nido|niño|ninho|map|mapa|distribution/i },
  orientalis: { titles: ["Vespa orientalis 2.jpg", "Oriental hornet (Vespa orientalis).jpg", "Vespa orientalis.queen.jpg"],
    search: "Vespa orientalis", must: /orientalis/i, not: /nest|nid|nido|map|mapa|distribution/i },
  crabro: { titles: ["Frelon europeen.jpg", "Vespa crabro by Sven Teschke.jpg"],
    search: "Vespa crabro", must: /crabro/i, not: /nest|nid|nido|map|mapa/i },
  nest_velutina: { titles: ["Vespa velutina nest.JPG", "Nido primario de una vespa velutina.jpg", "Vespa velutina nest Paslières n01.jpg"],
    search: "Vespa velutina nest", must: /velutina.*(nest|nid|nido|niño|ninho)|(nest|nid|nido|niño|ninho).*velutina|frelons? asiatiques?/i },
  nest_orientalis: { titles: ["Vespa orientalis nest 1.jpg"],
    search: "Vespa orientalis nest", must: /orientalis.*(nest|nid|nido)|(nest|nid|nido).*orientalis/i },
  nest_crabro: { titles: ["Vespa crabro nest full.jpg", "The European hornet nest (Vespa crabro).jpg"],
    search: "Vespa crabro nest", must: /crabro.*(nest|nid|nido)|(nest|nid|nido).*crabro/i }
};

const plain = (html) => String(html || "").replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();

async function api(params) {
  const q = new URLSearchParams({ format: "json", formatversion: "2", ...params });
  const res = await fetch(`${API}?${q}`, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`Commons API ${res.status}`);
  return res.json();
}

async function info(titles) {
  const data = await api({ action: "query", prop: "imageinfo", iiprop: "url|extmetadata|mime", iiurlwidth: String(WIDTH),
    titles: titles.map((t) => (t.startsWith("File:") ? t : "File:" + t)).join("|") });
  return (data.query?.pages || []).filter((p) => p.imageinfo?.[0] && /^image\/(jpeg|png)$/.test(p.imageinfo[0].mime)
    && !EXCLUDE.has(p.title.replace(/^File:/, "")));
}

async function searchTitles(g) {
  const data = await api({ action: "query", list: "search", srnamespace: "6", srlimit: "30", srsearch: g.search });
  return (data.query?.search || []).map((s) => s.title)
    .filter((t) => g.must.test(t) && !(g.not && g.not.test(t)) && /\.(jpe?g|png)$/i.test(t));
}

async function pick(key, g) {
  let pages = await info(g.titles);
  const fromSearch = [];
  if (pages.length < PER_GROUP) {
    const have = new Set(pages.map((p) => p.title));
    const extra = (await searchTitles(g)).filter((t) => !have.has(t)).slice(0, 10);
    const more = extra.length ? await info(extra) : [];
    for (const p of more) if (pages.length < PER_GROUP) { pages.push(p); fromSearch.push(p.title); }
  }
  return { key, pages: pages.slice(0, PER_GROUP), fromSearch };
}

async function save(key, i, page) {
  const ii = page.imageinfo[0];
  const ext = ii.mime === "image/png" ? "png" : "jpg";
  const name = `img/photos/${key}-${i + 1}.${ext}`;
  const res = await fetch(ii.thumburl || ii.url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`download ${res.status} ${page.title}`);
  writeFileSync(join(ROOT, name), Buffer.from(await res.arrayBuffer()));
  const m = ii.extmetadata || {};
  return { src: name, title: page.title.replace(/^File:/, ""), page: ii.descriptionurl,
    author: plain(m.Artist?.value) || "?", license: plain(m.LicenseShortName?.value), licenseUrl: m.LicenseUrl?.value || "" };
}

function writeOutputs(photos) {
  writeFileSync(join(ROOT, "src/photos.js"),
    "// Generated by tools/fetch_photos.mjs from Wikimedia Commons. Do not edit by hand.\n" +
    `export const PHOTOS = ${JSON.stringify(photos, null, 2)};\n`);
  const files = Object.values(photos).flat().map((p) => `  "${p.src}",`).join("\n");
  const sw = readFileSync(join(ROOT, "sw.js"), "utf8")
    .replace(/(\/\/ PHOTOS:BEGIN\n)[\s\S]*?(\s*\/\/ PHOTOS:END)/, `$1${files}$2`)
    .replace(/const VERSION = "([^"]+)";/, `const VERSION = "vc-photos-${new Date().toISOString().slice(0, 16).replace(/[-:T]/g, "")}";`);
  writeFileSync(join(ROOT, "sw.js"), sw);
}

async function main() {
  const dir = join(ROOT, "img/photos");
  mkdirSync(dir, { recursive: true });
  readdirSync(dir).forEach((f) => unlinkSync(join(dir, f)));
  const photos = {};
  for (const [key, g] of Object.entries(GROUPS)) {
    const { pages, fromSearch } = await pick(key, g);
    photos[key] = [];
    for (const [i, p] of pages.entries()) photos[key].push(await save(key, i, p));
    console.log(`${key}: ${pages.length} photo(s)`);
    photos[key].forEach((p) => console.log(`   ${fromSearch.includes("File:" + p.title) || fromSearch.includes(p.title) ? "[CHECK] " : ""}${p.title}  (${p.author}, ${p.license})`));
  }
  writeOutputs(photos);
  console.log("\nDone. Lines marked [CHECK] came from a search: open them in img/photos. If one is wrong, add its title to EXCLUDE in this script and run it again.");
}

main().catch((e) => { console.error("ERROR:", e.message); process.exit(1); });
